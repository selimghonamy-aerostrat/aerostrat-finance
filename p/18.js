const IMP18_TAG='Researched Oct 2026';
function imp18Missing(){
  const have=new Set(state.airlines.map(a=>(String(a.country||'')+'|'+String(a.name||'')).toLowerCase()));
  const names=new Set(state.airlines.map(a=>String(a.name||'').toLowerCase()));
  return IMP18.filter(r=>!have.has((r[0]+'|'+r[1]).toLowerCase())&&!names.has(String(r[1]).toLowerCase()));
}
function imp18Add(){
  if(readOnly) return;
  const add=imp18Missing(); if(!add.length){ toast('All researched airlines are already in the pipeline.'); return; }
  const pid=(state.products[0]||{}).id||'bundle';
  add.forEach(([country,name,fleet,asOf,src])=>{
    state.airlines.push({id:uid('a'),name,country,fleet,pilots:'',cabin:'',instructors:'',admins:'',product:pid,cohort:'',signMonth:'',goLiveMonth:'',
      status:'Pipeline',prob:10,billing:'annual',discount:0,growth:0,implOverride:'',include:false,
      notes:IMP18_TAG+': fleet '+fleet+(asOf?' (as of '+asOf+')':'')+(src?' · '+String(src).replace(/^wp:/,'https://en.wikipedia.org/wiki/'):''),renewProb:'',
      contact:{name:'',role:'',email:'',phone:''},nextAction:'',nextActionDate:'',stageLog:[],baselineSign:''});
  });
  commit();
  toast(add.length+' airlines added to the pipeline. Review them, then click Save to keep them.');
}
const pipelineBase18=pipeline;
pipeline=function(){
  const h=pipelineBase18(), miss=imp18Missing();
  if(readOnly||!miss.length) return h;
  const ctys=new Set(miss.map(r=>r[0]));
  const banner='<div class="banner"><span class="grow"><b>'+miss.length+' researched airlines in '+ctys.size+' countries</b> are ready to add (fleet sizes from Wikipedia, airline websites and aviation press, Oct 2026; source in each airline’s notes). They go in unticked in the Forecast, so your forecast does not change.</span><button class="btn small cta-outline" data-act="imp18-add">Add them to the pipeline</button></div>';
  const k=h.indexOf('<div class="region-strip');
  return k>=0?h.slice(0,k)+banner+h.slice(k):banner+h;
};
